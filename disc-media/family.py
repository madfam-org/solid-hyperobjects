"""
Disc Media — Yantra4D Hyperobject Cartridge (CadQuery / B-Rep).

The archetype of a game disc: a revolved disc (diameter, centre hole, thickness,
clamp zone, stacking ring), optionally carried in a shell with a window, a read
slot and a sliding shutter — the disc-in-shell formats (a UMD-type cartridge, a
square-shell disk). Standard discs take every number from the keystone's
standard parts; proprietary formats arrive as presets from its reference catalog.

COMPOSITION — a medium is a hyperobject of hyperobjects
--------------------------------------------------------
    component            module       CDG interface it exposes / consumes
    ------------------   ----------   -----------------------------------------
    revolved_disc        disc_media   exposes centre_hole, outline (the
                                      standard parts' own interface ids)
    disc_shell_outline   disc_media   exposes media_envelope
    disc_shell_boss      disc_media   exposes media_envelope (max thickness)
    disc_pocket          disc_media   — (the void the disc turns in)
    disc_window          disc_media   exposes disc_window
    disc_read_slot       disc_media   exposes read_window
    disc_shutter_track   disc_media   — (the track the shutter slides in)
    disc_shutter_plate   disc_media   exposes media_shutter

TWO FILES. This file, `family.py`, is the authored half; `main.py` is generated by
`tools/inline_parts.py` (ruling R2 on gate H8). Edit this file or the module,
never main.py, then run `python3 tools/inline_parts.py --write disc-media`.

This is a FAMILY, not a product: no logo, no label art, no surface pattern.

Frame (docs/README.md repeats it). The disc lies in XY, +Z through it from the
read-out side (z = 0) to the label side. In `disc` mode the centre hole is at the
origin. The shell's bounding rectangle is centred on the origin, `shell_width` in
X and `shell_length` in Y, occupying z from 0 upward; the disc sits in it at
(0, disc_center_y), centred in the shell's thickness.

Parts (dispatched on `target_part`):
  - disc        : the revolved disc, its centre hole at the origin (`disc` mode).
  - loaded_disc : the same disc in its pocket (`shell` mode).
  - shell    : the shell with its pocket, window, read slot and shutter track.
  - shutter  : the shutter plate, slid `shutter_open` of its travel.
  - envelope : one body — the shell's hull with its boss when `shell_present`,
               otherwise the disc's cylinder at its diameter and maximum height
               (the standard parts' own envelope solid: the hole is not cut).

Sandbox contract: `cq` and `math` are pre-injected; parameters arrive as BARE
globals read through PARAM(); the final solid is assigned to `result`.
"""

import math  # noqa: F401 — injected by the sandbox; imported so the file runs standalone

import cadquery as cq  # noqa: F401 — the inlined components below use it


def PARAM(getter, default):
    """Return an injected global if present, else the default."""
    try:
        v = getter()
        return default if v is None else v
    except Exception:
        return default


# ── Parameters ───────────────────────────────────────────────────────────────
# Every default is the archetype's own, generated by tools/presets/disc_media.py.

# L0 — disc
disc_diameter = float(PARAM(lambda: disc_diameter, 70.0))
disc_hole = float(PARAM(lambda: disc_hole, 10.0))
disc_thickness = float(PARAM(lambda: disc_thickness, 1.0))
clamp_inner_diameter = float(PARAM(lambda: clamp_inner_diameter, 18.0))
clamp_outer_diameter = float(PARAM(lambda: clamp_outer_diameter, 24.0))
clamp_relief = float(PARAM(lambda: clamp_relief, 0.1))
ring_width = float(PARAM(lambda: ring_width, 1.0))
ring_height = float(PARAM(lambda: ring_height, 0.2))

# L0 — shell
shell_present = bool(PARAM(lambda: shell_present, True))
shell_outline = str(PARAM(lambda: shell_outline, "rounded_rect"))
shell_width = float(PARAM(lambda: shell_width, 80.0))
shell_length = float(PARAM(lambda: shell_length, 84.0))
shell_thickness = float(PARAM(lambda: shell_thickness, 5.0))
shell_corner_radius = float(PARAM(lambda: shell_corner_radius, 3.0))
shell_top_arc_radius = float(PARAM(lambda: shell_top_arc_radius, 40.0))
shell_bottom_arc_radius = float(PARAM(lambda: shell_bottom_arc_radius, 100.0))
shell_boss_diameter = float(PARAM(lambda: shell_boss_diameter, 0.0))
shell_boss_height = float(PARAM(lambda: shell_boss_height, 0.0))
disc_center_y = float(PARAM(lambda: disc_center_y, 2.0))
pocket_clearance = float(PARAM(lambda: pocket_clearance, 0.3))

# L1 — window, read slot, shutter
window_width = float(PARAM(lambda: window_width, 35.0))
window_length = float(PARAM(lambda: window_length, 17.5))
window_offset_y = float(PARAM(lambda: window_offset_y, 14.0))
read_slot_width = float(PARAM(lambda: read_slot_width, 11.9))
read_slot_length = float(PARAM(lambda: read_slot_length, 21.0))
spindle_diameter = float(PARAM(lambda: spindle_diameter, 11.9))
shutter_overlap = float(PARAM(lambda: shutter_overlap, 2.0))
shutter_thickness = float(PARAM(lambda: shutter_thickness, 0.5))
shutter_open = float(PARAM(lambda: shutter_open, 0.0))

target_part = str(PARAM(lambda: target_part, "disc"))


# ═════════════════════════════════════════════════════════════════════════════
# COMPONENTS — authored once in commons-lib/hardware/, inlined below.
# ═════════════════════════════════════════════════════════════════════════════

# inline-parts: disc_media


# ═════════════════════════════════════════════════════════════════════════════
# ASSEMBLY — the only code that maps this manifest's parameters onto component
# dicts. Everything above is portable; everything below is this cartridge.
# ═════════════════════════════════════════════════════════════════════════════

DISC_HEIGHT = disc_thickness + max(ring_height, 0.0)
POCKET_HEIGHT = DISC_HEIGHT + 2.0 * pocket_clearance
SLOT_CENTER_Y = disc_center_y - (spindle_diameter / 2.0 + 1.0 + read_slot_length / 2.0)
PLATE_W = read_slot_width + 2.0 * shutter_overlap
PLATE_L = read_slot_length + 2.0 * shutter_overlap
TRACK_DEPTH = shutter_thickness + 0.05


def _disc():
    return revolved_disc({
        "diameter": disc_diameter, "hole": disc_hole, "thickness": disc_thickness,
        "clamp_inner": clamp_inner_diameter, "clamp_outer": clamp_outer_diameter,
        "clamp_relief": clamp_relief, "ring_width": ring_width,
        "ring_height": ring_height,
    })


def _hull():
    hull = disc_shell_outline({
        "shape": shell_outline, "width": shell_width, "length": shell_length,
        "thickness": shell_thickness, "corner_radius": shell_corner_radius,
        "top_arc_radius": shell_top_arc_radius,
        "bottom_arc_radius": shell_bottom_arc_radius,
    })
    if shell_boss_diameter > 0 and shell_boss_height > 0:
        hull = hull.union(disc_shell_boss({
            "diameter": shell_boss_diameter, "height": shell_boss_height,
            "center_y": disc_center_y, "face_z": shell_thickness,
        }))
    return hull


def disc_part():
    return _disc()


def loaded_disc_part():
    """The disc in its pocket: centred in the shell's thickness, at the disc centre."""
    return _disc().translate((0.0, disc_center_y, shell_thickness / 2.0 - DISC_HEIGHT / 2.0))


def shell_part():
    s = _hull()
    s = s.cut(disc_pocket({
        "diameter": disc_diameter + 2.0 * pocket_clearance, "height": POCKET_HEIGHT,
        "center_y": disc_center_y, "center_z": shell_thickness / 2.0,
    }))
    s = s.cut(disc_window({
        "width": window_width, "length": window_length,
        "center_y": disc_center_y + window_offset_y, "from_z": shell_thickness / 2.0,
        "top_z": shell_thickness + max(shell_boss_height, 0.0),
    }))
    s = s.cut(disc_read_slot({
        "spindle_diameter": spindle_diameter, "slot_width": read_slot_width,
        "slot_length": read_slot_length, "slot_center_y": SLOT_CENTER_Y,
        "disc_center_y": disc_center_y, "to_z": shell_thickness / 2.0,
    }))
    return s.cut(disc_shutter_track({
        "width": PLATE_W, "length": PLATE_L, "center_y": SLOT_CENTER_Y,
        "travel": PLATE_W, "depth": TRACK_DEPTH,
    }))


def shutter_part():
    return disc_shutter_plate({
        "width": PLATE_W - 0.4, "length": PLATE_L - 0.4,
        "thickness": shutter_thickness, "center_y": SLOT_CENTER_Y,
        "offset": max(0.0, min(1.0, shutter_open)) * PLATE_W, "lift": 0.02,
    })


def envelope_part():
    if shell_present:
        return _hull()
    return (
        cq.Workplane("XY")
        .cylinder(DISC_HEIGHT, disc_diameter / 2.0)
        .translate((0.0, 0.0, DISC_HEIGHT / 2.0))
    )


BUILDERS = {
    "disc": disc_part,
    "loaded_disc": loaded_disc_part,
    "shell": shell_part,
    "shutter": shutter_part,
    "envelope": envelope_part,
}

result = BUILDERS.get(target_part, disc_part)()
