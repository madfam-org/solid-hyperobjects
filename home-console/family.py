"""
Home Console — Yantra4D Hyperobject Cartridge (CadQuery / B-Rep).

One parametric desktop console, Odyssey and Channel F (wedge) to the PS5 (tower
with side covers and a stand seat), add-on boxes and mini consoles. Named
consoles are only presets generated from the keystone's reference catalog; the
default and every `archetype-*` preset are no product. No logos, no text, no
glyphs, no curve fitted to a photograph (ruling R3). docs/README.md has the
frame table, the modes, the composition and the archetype rules.

THE BODY is a ruled LOFT of rounded cross-sections (console_shell.shell_body).
`body_plan` chooses the construction — slab/tower/cube: one run at body_height;
wedge: front_height to front_break_y, rising to body_height at the rear;
upright: body_height to front_break_y, falling to rear_height; stepped: a base
at body_height - upper_tier_height plus an `upper_tier`, fused once (0.2 mm
bite). Crown, draft, concavity, skew and the three radii shape every section.

Frame: X = body_width (centred), Y = body_depth (front face at -D/2), Z =
body_height (flat bottom at 0, feet below). orientation_tilt_deg turns the
console about its bottom-right edge onto its side (90 = standing).

Parts: body (core + feet + handle fused; side covers as separate bodies),
closure (lid / tray / door / flaps / blank), envelope (the fused outline,
W x D x H exactly), top_shell / bottom_shell (hollow, split at the seam).

TWO FILES: this is `family.py`; `main.py` is generated by
`python3 tools/inline_parts.py --write home-console`. Never edit main.py.
Sandbox: parameters are bare globals read through PARAM; the result is `result`.
"""

