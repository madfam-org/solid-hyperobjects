def _secs(h_total, depth, drop):
    """Base-run sections [[y_from_front, height]] for the body plan."""
    fb = min(max(front_break_y, 0.0), depth) * depth / body_depth
    if body_plan == "wedge":
        s = [[0.0, front_height], [fb, front_height], [depth, h_total]]
    elif body_plan == "upright":
        s = [[0.0, h_total], [fb, h_total], [depth, rear_height]]
    elif body_plan == "stepped":
        s = [[0.0, h_total - upper_tier_height], [depth, h_total - upper_tier_height]]
    else:
        s = [[0.0, h_total], [depth, h_total]]
    if fb < 1.0 and len(s) == 3:
        s = [s[0], s[2]]
    return [[y, h - drop] for y, h in s]


def context(core):
    """Dimensions of the full outline (core=False) or of the covered core."""
    n = side_cover_count if core else 0
    ov = side_cover_overhang if n else 0.0
    w = body_width - n * (side_cover_thickness + COVER_GAP)
    cx = -(side_cover_thickness + COVER_GAP) / 2.0 if n == 1 else 0.0
    d = body_depth - 2.0 * ov
    ctx = {"w": w, "d": d, "cx": cx, "top": body_height - ov, "secs": _secs(body_height, d, ov)}
    ctx["tier"] = None
    if body_plan == "stepped":
        y0 = min(front_break_y, body_depth) * d / body_depth
        y1 = d - upper_tier_inset_y
        ctx["tier"] = {"w": w - 2.0 * upper_tier_inset_x, "d": y1 - y0,
                       "cy": -d / 2.0 + (y0 + y1) / 2.0, "y0": y0, "y1": y1,
                       "bottom": ctx["secs"][0][1] - crown - BITE}
    return ctx


def body_dict(ctx, inset=0.0):
    t = inset
    return {
        "width": ctx["w"] - 2 * t, "depth": ctx["d"] - 2 * t,
        "sections": [[y * (ctx["d"] - 2 * t) / ctx["d"], h - 2 * t] for y, h in ctx["secs"]],
        "crown": crown, "draft_deg": side_draft_deg, "concavity": side_concavity,
        "corner_radius_top": max(corner_radius_top - t, 0.0),
        "edge_chamfer": 0.0 if t else edge_chamfer,
        "corner_radius_plan": max(corner_radius_vertical - t, 0.0),
        "skew_deg": plan_skew_deg, "center_x": ctx["cx"], "center_y": 0.0, "base_z": t,
    }


def tier_dict(ctx, inset=0.0):
    tr = ctx["tier"]
    return {
        "width": tr["w"] - 2 * inset, "depth": tr["d"] - 2 * inset,
        "top_z": ctx["top"] - inset, "bottom_z": tr["bottom"] - (inset + 1.0 if inset else 0.0),
        "crown": crown, "draft_deg": side_draft_deg,
        "corner_radius_top": max(corner_radius_top - inset, 0.0),
        "corner_radius_plan": max(corner_radius_vertical - inset, 0.0),
        "skew_deg": plan_skew_deg, "center_x": ctx["cx"], "center_y": tr["cy"],
    }


def outline(ctx):
    """The fused outline: base run + tier (one solid)."""
    solid = shell_body(body_dict(ctx)).val()
    if ctx["tier"] is not None:
        solid = solid.fuse(upper_tier(tier_dict(ctx)).val()).clean()
    return solid


def surf_top(ctx, x, y):
    yf = min(max(y + ctx["d"] / 2.0, 0.0), ctx["d"])
    secs = ctx["secs"]
    h = secs[-1][1]
    for (y0, h0), (y1, h1) in zip(secs, secs[1:]):
        if yf <= y1:
            h = h0 + (h1 - h0) * (yf - y0) / max(y1 - y0, 1e-9)
            break
    h -= crown * min(((x - ctx["cx"]) / (ctx["w"] / 2.0)) ** 2, 1.0)
    tr = ctx["tier"]
    if tr and abs(x - ctx["cx"]) < tr["w"] / 2.0 and tr["y0"] <= yf <= tr["y1"]:
        h = max(h, ctx["top"] - crown * ((x - ctx["cx"]) / (tr["w"] / 2.0)) ** 2)
    return h


def frame(ctx, face, u, v):
    return face_frame({"face": face, "u": u, "v": v, "width": ctx["w"], "depth": ctx["d"],
                       "top": ctx["top"], "center_x": ctx["cx"]})


def extra(ctx, face, u, v, hu, hv):
    """How far inside the outer plane the real surface lies, at worst, over a footprint."""
    tan_s = math.tan(math.radians(plan_skew_deg))
    if face == "top":
        return ctx["top"] - min(surf_top(ctx, u + i * hu, v + j * hv)
                                for i in (-1, 0, 1) for j in (-1, 0, 1))
    if face == "front":
        return max(v + hv, 0.0) * tan_s
    if face == "rear":
        return max(ctx["secs"][-1][1] - max(v - hv, 0.0), 0.0) * tan_s
    if face in ("left", "right"):
        return max(v + hv, 0.0) * math.tan(math.radians(side_draft_deg)) + side_concavity
    return 0.0


def disc_frame(ctx):
    """The front frame a tray or slot loader sits in: turned upright (local X up)
    on a body taller than it is wide, as a standing console's drive is."""
    fr = frame(ctx, "front", ctx["cx"], tray_center_z)
    if body_height > body_width:
        fr["x_dir"] = (0, 0, 1)
    return fr


def rect_tool(ctx, face, u, v, w, h, depth):
    plane = face_plane(frame(ctx, face, u, v))
    total = depth + extra(ctx, face, u, v, w / 2.0, h / 2.0) + OVER
    return cq.Workplane(plane).workplane(offset=OVER).rect(w, h).extrude(-total)


def yz_port(ctx, face, x, z, shape, w, h):
    """A front or rear opening through the existing connectors.port_receptacle."""
    s = 1.0 if face == "rear" else -1.0
    depth = PORT_DEPTH + extra(ctx, face, x, z, w / 2.0, h / 2.0) + OVER
    return port_receptacle({
        "shape": shape, "width": w, "height": h, "depth": depth, "radius": w / 2.0,
        "center_x": x, "center_y": s * (ctx["d"] / 2.0 + OVER - depth / 2.0), "center_z": z,
    })


def mouth(ctx):
    """(face, u, v, width, thickness) of a slot-type medium's opening."""
    mk = media_kind
    if mk in ("cart_top", "disc_and_cart", "none"):
        thick = media_width * 0.6 if mk == "none" else media_thickness
        return "top", slot_center_x, slot_center_y, media_width, thick
    if mk == "disc_slot":
        return "front", ctx["cx"], tray_center_z, disc_diameter, DISC_THICKNESS
    return ("rear" if mk == "cart_rear" else "front"), slot_center_x, slot_center_z, \
        media_width, media_thickness


