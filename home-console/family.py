def closure_part(ctx):
    """The part that closes the media opening, posed by lid_angle / tray_extension."""
    mk, c = media_kind, slot_clearance
    if mk in ("disc_lid", "disc_and_cart"):
        return disc_lid({"frame": frame(ctx, "top", lid_center_x, lid_center_y),
                         "lid_diameter": lid_diameter, "thickness": LID_THICKNESS, "gap": GAP,
                         "drop": ctx["top"] - surf_top(ctx, lid_center_x, lid_center_y),
                         "angle": lid_angle})
    if mk == "disc_tray":
        return disc_tray({"frame": disc_frame(ctx), "width": tray_width, "height": tray_height,
                          "depth": disc_diameter + 6.0, "gap": GAP, "disc_diameter": disc_diameter,
                          "pocket_depth": 1.5, "extension": tray_extension,
                          "travel": disc_diameter + 10.0})
    face, u, v, w, t = mouth(ctx)
    fr = disc_frame(ctx) if mk == "disc_slot" else frame(ctx, face, u, v)
    if face == "top":   # sit on the real surface, not the top plane
        fr["origin"] = (u, v, surf_top(ctx, u, v))
    w, h = w + 2 * c, t + 2 * c
    if mk == "none":
        return slot_blank({"frame": fr, "width": w, "height": h, "plug_depth": 1.5 - GAP,
                           "gap": GAP, "flange": False, "flange_margin": 0.0, "flange_thickness": 0.0})
