#!/usr/bin/env python3
"""Generate a family cartridge's `main.py` from its `family.py` and commons-lib/hardware/.

Usage:
  inline_parts.py --write SLUG [SLUG ...]   regenerate those cartridges' main.py
  inline_parts.py --check [SLUG ...]        fail on any drift (default: every slug
                                            that has a family.py)

Why (ruling R2 on gate H8, 2026-11-01). The CadQuery render sandbox blocks `sys`,
`os` and `importlib`, so a cartridge can never import a shared component, and an
installed parts package would move geometry with no cartridge diff — the render
lane would never see it. So a component is authored ONCE, as canonical text in
`commons-lib/hardware/<module>.py`, and copied into every family that uses it:

  * `<slug>/family.py` is the authored source. Exactly one line in it reads
    `# inline-parts: <module> [<module> ...]`; that line is where the modules go.
  * Each module's leading comment block carries `# requires: [<module> ...]`.
    Requirements are inlined first, once each, in declaration order.
  * `<slug>/main.py` is GENERATED: a three-line banner, then family.py with every
    module's text between `# BEGIN commons-lib/hardware/<m>.py@<git-blob-sha>`
    and `# END commons-lib/hardware/<m>.py@<git-blob-sha>`, verbatim. The sha is
    `git hash-object` of the module file, computed here without git.

`--check` regenerates every family in memory and compares bytes, so a module
edited without a regeneration, a hand-edited inline copy and a family.py edited
without one all fail the same way. It also fails a `main.py` that carries markers
but has no family.py, and lints every module (see `lint_module`) whether or not a
family inlines it yet. Pure stdlib: it runs in the manifests lane, no CAD kernel.

`load(names)` executes the same texts, in the same order, into one namespace —
the composition a generated main.py runs — so the modules are testable outside
the sandbox.
"""

import argparse
import ast
import difflib
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HARDWARE = "commons-lib/hardware"
FAMILY_FILE = "family.py"
MAIN_FILE = "main.py"
SPDX_LINE = "# SPDX-License-Identifier: CERN-OHL-W-2.0"
MAX_MODULE_LINES = 600
#: What the sandbox lets a component import (it injects both as globals anyway).
ALLOWED_IMPORTS = {"math", "cadquery"}

MODULE_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
DIRECTIVE = re.compile(r"^# inline-parts:(.*)$")
REQUIRES = re.compile(r"^# requires:(.*)$")
MARKER = re.compile(r"^# (BEGIN|END) commons-lib/hardware/([a-z][a-z0-9_]*)\.py@([0-9a-f]{40})$")
CONSTANT = re.compile(r"^[A-Z][A-Z0-9_]*$")


class InlineError(Exception):
    """A family or a module the inliner refuses to compose."""


def blob_sha(data: bytes) -> str:
    """`git hash-object` of `data`: sha1 over `blob <len>\\0` + data."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def begin_marker(name, sha):
    return f"# BEGIN {HARDWARE}/{name}.py@{sha}"


def end_marker(name, sha):
    return f"# END {HARDWARE}/{name}.py@{sha}"


def banner(slug):
    return (
        f"# GENERATED by tools/inline_parts.py from {FAMILY_FILE} + {HARDWARE}/ — do not edit.\n"
        f"# Edit {FAMILY_FILE} or the module, then run: python3 tools/inline_parts.py --write {slug}\n"
        "# ruff: noqa: E402, F811 — every inlined module repeats its own `import cadquery as cq`\n"
    )


def _header_comments(lines):
    """The leading run of `#` comment lines."""
    out = []
    for line in lines:
        if not line.startswith("#"):
            break
        out.append(line)
    return out


def _top_level_names(tree):
    """Names a top-level statement binds: defs, classes and plain assignments."""
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                names.update(n.id for n in ast.walk(target) if isinstance(n, ast.Name))
    return names


def lint_module(name, text):
    """Problems with one module's text, or [] — the rules a component lives by.

    A module is executed at the top of every family that inlines it, inside the
    sandbox, so it may only define things: a docstring, `import math` /
    `import cadquery as cq`, functions and UPPER_CASE constants. Anything else is
    code that would run in N cartridges at once.
    """
    problems = []
    lines = text.split("\n")
    if not text.endswith("\n") or text.endswith("\n\n"):
        problems.append("must end with exactly one newline")
    if lines[0] != SPDX_LINE:
        problems.append(f"first line must be `{SPDX_LINE}`")
    if text.count("\n") > MAX_MODULE_LINES:
        problems.append(f"{text.count(chr(10))} lines; a module stays at or under {MAX_MODULE_LINES}")
    header = _header_comments(lines)
    if sum(1 for line in header if REQUIRES.match(line)) != 1:
        problems.append("needs exactly one `# requires:` line in its leading comment block")
    if any(MARKER.match(line) or DIRECTIVE.match(line) for line in lines):
        problems.append("must not contain an inline marker or an `# inline-parts:` directive")
    try:
        tree = ast.parse(text, filename=f"{HARDWARE}/{name}.py")
    except SyntaxError as exc:
        return problems + [f"does not parse: {exc}"]
    for i, node in enumerate(tree.body):
        if i == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            continue  # the docstring
        if isinstance(node, ast.Import):
            bad = [a.name for a in node.names if a.name not in ALLOWED_IMPORTS]
            if bad:
                problems.append(f"line {node.lineno}: imports {', '.join(bad)} "
                                f"(only {', '.join(sorted(ALLOWED_IMPORTS))} reach the sandbox)")
            continue
        if isinstance(node, ast.FunctionDef):
            continue
        if isinstance(node, ast.Assign) and all(
                isinstance(t, ast.Name) and CONSTANT.match(t.id) for t in node.targets):
            continue
        problems.append(f"line {node.lineno}: top-level {type(node).__name__} — a module "
                        "may only hold a docstring, imports, functions and UPPER_CASE constants")
    return problems


def read_module(root, name):
    """(text, sha, requires, defined names) for one module, or InlineError."""
    if not MODULE_NAME.match(name):
        raise InlineError(f"`{name}` is not a module name (^[a-z][a-z0-9_]*$)")
    path = Path(root) / HARDWARE / f"{name}.py"
    if not path.is_file():
        raise InlineError(f"{HARDWARE}/{name}.py does not exist")
    data = path.read_bytes()
    text = data.decode("utf-8")
    problems = lint_module(name, text)
    if problems:
        raise InlineError(f"{HARDWARE}/{name}.py: " + "; ".join(problems))
    header = _header_comments(text.split("\n"))
    requires = next(REQUIRES.match(line).group(1).split() for line in header if REQUIRES.match(line))
    return {"name": name, "text": text, "sha": blob_sha(data), "requires": requires,
            "names": _top_level_names(ast.parse(text))}


def resolve(root, names):
    """The modules to inline for `names`, requirements first, each once."""
    order, done, active = [], set(), []

    def visit(name):
        if name in done:
            return
        if name in active:
            raise InlineError("requirement cycle: " + " -> ".join(active + [name]))
        active.append(name)
        module = read_module(root, name)
        for req in module["requires"]:
            visit(req)
        active.pop()
        done.add(name)
        order.append(module)

    for name in names:
        visit(name)
    return order


def parse_family(text, where):
    """(lines, directive index, declared module names) of a family.py."""
    lines = text.split("\n")
    hits = [i for i, line in enumerate(lines) if DIRECTIVE.match(line)]
    if len(hits) != 1:
        raise InlineError(f"{where}: needs exactly one `# inline-parts:` line, found {len(hits)}")
    declared = DIRECTIVE.match(lines[hits[0]]).group(1).split()
    if not declared:
        raise InlineError(f"{where}: the `# inline-parts:` line names no module")
    if len(set(declared)) != len(declared):
        raise InlineError(f"{where}: a module is named twice on the `# inline-parts:` line")
    if any(MARKER.match(line) for line in lines):
        raise InlineError(f"{where}: carries inline markers — it is the authored source, not output")
    return lines, hits[0], declared


def generate(root, slug):
    """The main.py text `slug`'s family.py and modules produce."""
    where = f"{slug}/{FAMILY_FILE}"
    path = Path(root) / slug / FAMILY_FILE
    if not path.is_file():
        raise InlineError(f"{where} does not exist")
    text = path.read_text(encoding="utf-8")
    lines, at, declared = parse_family(text, where)
    modules = resolve(root, declared)

    owner = {}
    for module in modules:
        for defined in sorted(module["names"]):
            if defined in owner:
                raise InlineError(f"`{defined}` is defined by both {owner[defined]}.py and "
                                  f"{module['name']}.py")
            owner[defined] = module["name"]
    try:
        family_names = _top_level_names(ast.parse(text, filename=where))
    except SyntaxError as exc:
        raise InlineError(f"{where} does not parse: {exc}") from exc
    shadowed = sorted(family_names & set(owner))
    if shadowed:
        raise InlineError(f"{where} redefines {', '.join(shadowed)}, which "
                          f"{HARDWARE} provides — the inlined component would be overridden")

    blocks = [begin_marker(m["name"], m["sha"]) + "\n" + m["text"] + end_marker(m["name"], m["sha"]) + "\n"
              for m in modules]
    before = "\n".join(lines[: at + 1]) + "\n"
    after = "\n".join(lines[at + 1 :])
    return banner(slug) + before + "\n\n" + "\n\n".join(blocks) + after


def family_slugs(root):
    return sorted(p.parent.name for p in Path(root).glob(f"*/{FAMILY_FILE}"))


def inlined_blocks(text):
    """[(name, sha, body)] of every BEGIN/END block in a generated main.py."""
    blocks, open_ = [], None
    for line in text.split("\n"):
        match = MARKER.match(line)
        if not match:
            if open_ is not None:
                open_[2].append(line)
            continue
        kind, name, sha = match.groups()
        if kind == "BEGIN":
            open_ = (name, sha, [])
        elif open_ is not None and open_[:2] == (name, sha):
            blocks.append((name, sha, "\n".join(open_[2]) + "\n"))
            open_ = None
    return blocks


def _diagnose(root, slug, current):
    """Why a main.py differs from what its family would generate."""
    reasons = []
    for name, sha, body in inlined_blocks(current):
        if blob_sha(body.encode("utf-8")) != sha:
            reasons.append(f"the inline copy of {name}.py was edited by hand (it no longer "
                           f"hashes to its marker @{sha[:12]})")
            continue
        path = Path(root) / HARDWARE / f"{name}.py"
        if not path.is_file():
            reasons.append(f"{HARDWARE}/{name}.py no longer exists")
        elif blob_sha(path.read_bytes()) != sha:
            reasons.append(f"{HARDWARE}/{name}.py changed since main.py was generated "
                           f"(inlined @{sha[:12]}, now @{blob_sha(path.read_bytes())[:12]})")
    return reasons or [f"{FAMILY_FILE} changed since main.py was generated, or main.py was edited"]


def check(root, slugs=None):
    """Every problem across the families (and the modules), as strings."""
    root = Path(root)
    problems = []
    for path in sorted((root / HARDWARE).glob("*.py")):
        for problem in lint_module(path.stem, path.read_text(encoding="utf-8")):
            problems.append(f"{HARDWARE}/{path.name}: {problem}")
    families = family_slugs(root)
    for main in sorted(root.glob(f"*/{MAIN_FILE}")):
        slug = main.parent.name
        if slug not in families and any(MARKER.match(line) for line in
                                        main.read_text(encoding="utf-8", errors="replace").split("\n")):
            problems.append(f"{slug}/{MAIN_FILE} carries inline markers but {slug}/{FAMILY_FILE} "
                            "is missing — the generated file has no source")
    for slug in (families if slugs is None else slugs):
        try:
            expected = generate(root, slug)
        except InlineError as exc:
            problems.append(str(exc))
            continue
        main = root / slug / MAIN_FILE
        current = main.read_text(encoding="utf-8") if main.is_file() else ""
        if current == expected:
            continue
        diff = list(difflib.unified_diff(current.splitlines(), expected.splitlines(),
                                         f"{slug}/{MAIN_FILE} (committed)",
                                         f"{slug}/{MAIN_FILE} (generated)", lineterm="", n=1))
        problems.append(f"{slug}/{MAIN_FILE} drifted: " + "; ".join(_diagnose(root, slug, current))
                        + f". Run: python3 tools/inline_parts.py --write {slug}\n"
                        + "\n".join(diff[:40]))
    return problems


def load(names, root=ROOT):
    """Execute the modules `names` resolve to into ONE namespace, in inline order.

    The composition a generated main.py runs, minus the sandbox: what tests use to
    build a component outside a cartridge.
    """
    namespace = {"__name__": "commons_hardware"}
    for module in resolve(root, names):
        code = compile(module["text"], f"{HARDWARE}/{module['name']}.py", "exec")
        exec(code, namespace)  # noqa: S102 — first-party canonical text
    return namespace


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", nargs="+", metavar="SLUG", help="regenerate these cartridges")
    action.add_argument("--check", nargs="*", metavar="SLUG",
                        help="fail on drift (default: every slug with a family.py)")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.write:
        for slug in args.write:
            try:
                text = generate(args.root, slug)
            except InlineError as exc:
                print(f"inline_parts: {exc}", file=sys.stderr)
                return 1
            (args.root / slug / MAIN_FILE).write_text(text, encoding="utf-8")
            modules = [name for name, _, _ in inlined_blocks(text)]
            print(f"wrote {slug}/{MAIN_FILE} ({text.count(chr(10))} lines; inlined {' '.join(modules)})")
        return 0

    slugs = args.check or None
    problems = check(args.root, slugs)
    checked = slugs or family_slugs(args.root)
    for problem in problems:
        print(f"::error title=inline_parts::{problem.splitlines()[0]}")
        print(problem)
    print(f"inline_parts --check: {len(checked)} family cartridge(s) "
          f"({' '.join(checked) or 'none'}), {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
