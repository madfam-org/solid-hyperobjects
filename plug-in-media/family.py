SIDE = insertion_edge == "side"
# The canonical frame: contact edge at z = 0, `CW` across it, `CH` away from it.
CW, CH = (shell_height, shell_width) if SIDE else (shell_width, shell_height)
BAND = (not card_mode) and grip_thickness > shell_thickness and grip_height > 0
T_MAX = grip_thickness if BAND else shell_thickness


def _place(shape):
    return media_place(shape, {
        "insertion_edge": insertion_edge, "width": shell_width,
        "height": shell_height, "travel": insert_travel,
    })


def _outer():
    return media_shell_outer({
        "width": CW, "height": CH, "thickness": shell_thickness,
        "corner_radius": corner_radius,
        "grip_thickness": grip_thickness if BAND else 0.0,
        "grip_height": grip_height,
    })


def _shell():
    """The whole shell in the canonical frame, every feature cut, before the split."""
    s = _outer()
    if card_mode:
        if contact_window_width > 0:
            s = s.cut(contact_pocket({
                "width": contact_window_width, "depth": contact_window_depth,
                "recess": pcb_thickness, "face_y": shell_thickness / 2.0,
            }))
    else:
        s = s.cut(media_shell_cavity({
            "width": CW, "height": CH, "thickness": shell_thickness,
            "wall": shell_wall, "corner_radius": corner_radius,
        }))
        if contact_window_width > 0:
            s = s.cut(contact_window({
                "width": contact_window_width, "depth": contact_window_depth,
                "thickness": shell_thickness - 2.0 * shell_wall,
            }))
    for w, h, d, c, side in (
        (label_front_width, label_front_height, label_front_depth, label_front_center, -1.0),
        (label_back_width, label_back_height, label_back_depth, label_back_center, 1.0),
    ):
        if w > 0 and h > 0 and d > 0:
            s = s.cut(label_recess({
                "width": w, "height": h, "depth": d, "center_x": 0.0, "center_z": c,
                "face_y": side * shell_thickness / 2.0, "outer_y": side * T_MAX / 2.0,
            }))
    if grip_ridge_count > 0:
        s = s.cut(grip_ridges({
            "count": grip_ridge_count, "pitch": grip_ridge_pitch,
            "depth": grip_ridge_depth, "groove_width": grip_ridge_pitch / 2.0,
            "first_z": CH - grip_ridge_pitch, "width": CW, "face_y": T_MAX / 2.0,
        }))
    if notch_count > 0:
        s = s.cut(keying_notches({
            "count": min(notch_count, 2), "width": notch_width, "depth": notch_depth,
            "offset": notch_offset, "shell_width": CW, "thickness": T_MAX,
        }))
    if shutter:
        s = s.cut(shutter_outline({
            "width": contact_window_width + 2.0 * shell_wall, "height": shutter_height,
            "bottom": shutter_gap + 0.5, "gap": shutter_gap,
            "depth": shutter_groove_depth, "face_y": shell_thickness / 2.0,
        }))
    if pass_through_slot:
        s = s.cut(pass_through_mouth({
            "width": pass_slot_width, "thickness": pass_slot_thickness,
            "depth": pass_slot_depth, "shell_height": CH,
        }))
    return s


def _half(side):
    reach = T_MAX / 2.0 + MEDIA_OVERSHOOT
    keep = (
        cq.Workplane("XY")
        .box(CW + 2.0 * MEDIA_OVERSHOOT, reach, CH + 2.0 * MEDIA_OVERSHOOT)
        .translate((0.0, side * reach / 2.0, CH / 2.0))
    )
    return _place(_shell().intersect(keep))


def front_shell_part():
    return _half(-1.0)


def back_shell_part():
    return _half(1.0)


def pcb_part():
    c = pcb_clearance
    per_front = edge_contacts // 2
    if card_mode:
        # The contact plate in the back-face pocket: no panel, contacts on +Y only.
        board = edge_connector_board({
            "thickness": pcb_thickness - 0.1,
            "center_y": shell_thickness / 2.0 - pcb_thickness / 2.0,
            "panel_width": 0.0, "panel_bottom": 0.0, "panel_top": 0.0,
            "tongue_width": contact_window_width - 2.0 * c,
            "tongue_bottom": c, "tongue_top": contact_window_depth - c,
            "front_contacts": 0, "back_contacts": edge_contacts,
            "pitch": edge_pitch, "pad_length": contact_window_depth - 2.0 * c - 1.0,
            "pad_inset": 0.5,
        })
        return _place(board)
    top = CH - shell_wall - c
    if pass_through_slot:
        top = min(top, CH - pass_slot_depth - c)
    tongue = contact_window_width - 2.0 * c if contact_window_width > 0 else 0.0
    board = edge_connector_board({
        "thickness": pcb_thickness, "center_y": 0.0,
        "panel_width": CW - 2.0 * shell_wall - 2.0 * c,
        "panel_bottom": shell_wall + c, "panel_top": top,
        "tongue_width": tongue if tongue > 0 else CW - 2.0 * shell_wall - 2.0 * c,
        "tongue_bottom": pcb_edge_recess if tongue > 0 else shell_wall + c,
        "tongue_top": shell_wall + c + MEDIA_BITE,
        "front_contacts": per_front if tongue > 0 else 0,
        "back_contacts": edge_contacts - per_front if tongue > 0 else 0,
        "pitch": edge_pitch,
        "pad_length": contact_window_depth - pcb_edge_recess - 1.0,
        "pad_inset": 0.3,
    })
    return _place(board)


def envelope_part():
    return _place(_outer())


BUILDERS = {
    "front_shell": front_shell_part,
    "back_shell": back_shell_part,
    "pcb_envelope": pcb_part,
    "envelope": envelope_part,
}

result = BUILDERS.get(target_part, envelope_part)()
