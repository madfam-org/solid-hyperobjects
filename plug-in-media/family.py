pass_through_slot = bool(PARAM(lambda: pass_through_slot, False))
pass_slot_width = float(PARAM(lambda: pass_slot_width, 70.0))
pass_slot_thickness = float(PARAM(lambda: pass_slot_thickness, 8.25))
