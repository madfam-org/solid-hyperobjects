"""
Plug-in Media — Yantra4D Hyperobject Cartridge (CadQuery / B-Rep).

The archetype of every medium that plugs in by a contact edge: a shell (two
halves split on the mid-plane), a board inside it whose tongue reaches a contact
window in one edge, and the features a slot registers against — keying notches,
a shutter door, a pass-through slot in the far edge, label recesses and generic
grip ridges. `card_mode` makes it a monolithic thin card whose contacts sit in a
shallow pocket in the back face. From a 1976 cartridge-with-a-door to a game
card, one family; named formats arrive as presets.

COMPOSITION — a medium is a hyperobject of hyperobjects
--------------------------------------------------------
    component              module          CDG interface it exposes / consumes
    --------------------   -------------   ----------------------------------------
    media_shell_outer      media_shells    exposes media_envelope
    media_shell_cavity     media_shells    — (the void the board lives in)
    contact_window         media_shells    exposes edge_connector (the mouth)
    contact_pocket         media_shells    exposes edge_connector (card mode)
    edge_connector_board   media_shells    exposes edge_connector (the fingers)
    label_recess           media_shells    exposes label_recess
    grip_ridges            media_shells    — (a grip is a surface)
    keying_notches         media_shells    exposes media_key
    shutter_outline        media_shells    exposes media_shutter
    pass_through_mouth     media_shells    consumes media_envelope (a 2nd medium)
    media_place            media_shells    the pose (insertion edge + travel)

TWO FILES. This file, `family.py`, is the authored half. `main.py` is generated
from it by `tools/inline_parts.py` (ruling R2 on gate H8). Edit this file or the
module, never main.py, then run `python3 tools/inline_parts.py --write plug-in-media`.

This is a FAMILY, not a product. No logo, no glyph, no artwork: a label is a
RECESS. Named formats carry published dimensions from the keystone's reference
catalog with a provenance line; every other number is the archetype's own.

Frame (docs/README.md repeats it):
    X  shell_width      across the label face; centred on x = 0
    Y  shell_thickness  through the shell; the label (front) face is -Y; the split
                        plane between the two halves is y = 0
    Z  shell_height     up the label face; the shell stands on z = 0
The catalog's `dimensions_mm.states.shell` {width, height, depth} maps to X, Z, Y.
`insertion_edge` names the label edge that carries the contacts (bottom, top,
side = +X); the shell is built with its contact edge at z = 0 and turned into
place by `media_place`, so the envelope never depends on it.

Parts (dispatched on `target_part`):
  - front_shell : the label half, y < 0.
  - back_shell  : the other half, y > 0 (the card's contact pocket, the shutter).
  - pcb_envelope: the board and its edge contacts (card mode: the contact plate).
  - envelope    : the plain hull, one body — the fit surface, and the bounding box
                  a preset asserts.

Sandbox contract (apps/api/services/engine/cq_runner.py): `cq` and `math` are
pre-injected; parameters arrive as BARE globals read through PARAM(); the final
solid is assigned to `result`.
"""

