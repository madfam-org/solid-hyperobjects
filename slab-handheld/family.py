import math
import cadquery as cq


def PARAM(getter, default):
    try:
        value=getter()
        return default if value is None else value
    except Exception:
        return default

body_width = PARAM(lambda: body_width, 170)
body_height = PARAM(lambda: body_height, 90)
body_depth = PARAM(lambda: body_depth, 26)
layout = PARAM(lambda: layout, 'landscape')
corner_radius = PARAM(lambda: corner_radius, 7.2)
back_crown = PARAM(lambda: back_crown, 2)
grip_count = PARAM(lambda: grip_count, 0)
face_depth = PARAM(lambda: face_depth, 26)
grip_width = PARAM(lambda: grip_width, 30.6)
grip_length = PARAM(lambda: grip_length, 67.5)
grip_drop = PARAM(lambda: grip_drop, 0)
screen_width = PARAM(lambda: screen_width, 88.4)
screen_height = PARAM(lambda: screen_height, 58.5)
screen_z = PARAM(lambda: screen_z, 47.7)
control_z = PARAM(lambda: control_z, 43.2)
control_x = PARAM(lambda: control_x, 66.3)
dpad_count = PARAM(lambda: dpad_count, 1)
face_count = PARAM(lambda: face_count, 4)
stick_count = PARAM(lambda: stick_count, 2)
system_count = PARAM(lambda: system_count, 2)
rear_count = PARAM(lambda: rear_count, 0)
crank_present = PARAM(lambda: crank_present, False)
control_size = PARAM(lambda: control_size, 12.6)
button_radius = PARAM(lambda: button_radius, 3.15)
media_kind = PARAM(lambda: media_kind, 'slot_top')
media_width = PARAM(lambda: media_width, 55)
media_height = PARAM(lambda: media_height, 28.8)
media_thickness = PARAM(lambda: media_thickness, 5)
media_insert_depth = PARAM(lambda: media_insert_depth, 16.2)
media_insert = PARAM(lambda: media_insert, 1)
cell_kind = PARAM(lambda: cell_kind, 'built_in')
cell_count = PARAM(lambda: cell_count, 0)
bay_width = PARAM(lambda: bay_width, 45)
bay_height = PARAM(lambda: bay_height, 18)
bay_depth = PARAM(lambda: bay_depth, 0)
bay_z = PARAM(lambda: bay_z, 27)
controller_attach = PARAM(lambda: controller_attach, 'none')
kickstand_present = PARAM(lambda: kickstand_present, True)
kickstand_angle = PARAM(lambda: kickstand_angle, 0)
kickstand_width = PARAM(lambda: kickstand_width, 42.5)
kickstand_height = PARAM(lambda: kickstand_height, 36)
usb_present = PARAM(lambda: usb_present, True)
jack_present = PARAM(lambda: jack_present, True)
wall = PARAM(lambda: wall, 2)
clearance = PARAM(lambda: clearance, 0.4)
recess_depth = PARAM(lambda: recess_depth, 1.2)
bumper_count = PARAM(lambda: bumper_count, 2)
trigger_count = PARAM(lambda: trigger_count, 0)
touchpad_present = PARAM(lambda: touchpad_present, False)
target_part = PARAM(lambda: target_part, "front_shell")

# inline-parts: displays controls handheld_body


def shape_params(inset=0):
    return dict(width=body_width-2*inset,height=body_height-2*inset,
        depth=body_depth-2*inset,face_depth=face_depth-2*inset,
        corner_radius=max(corner_radius-inset,0.2),back_crown=back_crown,
        grip_count=grip_count,grip_width=grip_width-2*inset,
        grip_length=grip_length-2*inset,grip_drop=grip_drop,
        grip_radius=max(min(grip_width,grip_length)*0.12-inset,0.2),
        grip_front_y=max(1,face_depth*0.4)-inset)


def outer():
    return slab_body(shape_params())


def media_params():
    kind="cart_rear" if media_kind=="faceplate" else media_kind
    return dict(kind=kind,width=media_width,height=media_height,thickness=media_thickness,
        clearance=clearance,insert_depth=media_insert_depth,center_x=0,
        center_y=face_depth*0.58,center_z=body_height*0.72,face_z=body_height,
        open_y=rear_y(shape_params(),media_width/2),back_y=body_depth,insert=media_insert)


def door_params():
    w,h,d=bay_width,bay_height,bay_depth
    if cell_kind in ("aa","aaa") and cell_count>0:
        # Keystone standard-part maxima (cell-aa/cell-aaa), kept equal by tests.
        dia,length=(14.5,50.5) if cell_kind=="aa" else (10.5,44.5)
        w,h,d=cell_bay_size(dict(diameter=dia,length=length,count=cell_count,axis="x",clearance=clearance))
    return dict(bay_width=w,bay_height=h,bay_depth=d,
        door_lip=1.5,door_thickness=1.5,door_clearance=clearance,
        center_x=0,center_z=max(bay_z,h/2+4),open_y=rear_y(shape_params(),(bay_width+3)/2),back_y=body_depth)


def stand_params():
    return dict(width=kickstand_width,height=kickstand_height,thickness=1.2,
        bite=0.8,center_x=body_width*0.28,top_z=body_height*0.82,
        hinge_y=rear_y(shape_params(),body_width*0.28)-0.8,angle=kickstand_angle,
        clearance=clearance,back_y=body_depth)


def front_tools():
    depth=recess_depth+1
    cz=face_cut_center(recess_depth)
    tools=[face_tool(display_panel(dict(width=screen_width,height=screen_height,
        recess_depth=depth,center_x=0,center_y=screen_z,cut_center_z=cz)))]
    x=-control_x; z=control_z if layout=="landscape" else body_height*0.25
    if dpad_count:
        tools.append(face_tool(d_pad(dict(arm_length=control_size,arm_width=control_size*0.35,
            recess_depth=depth,center_x=x,center_y=z,cut_center_z=cz))))
    if face_count:
        tools.append(face_tool(face_button(dict(count=face_count,spacing_deg=360/face_count,
            circle_radius=control_size*0.35,radius=button_radius,recess_depth=depth,
            center_x=control_x,center_y=z,cut_center_z=cz))))
    if stick_count:
        tools.append(face_tool(analog_stick(dict(count=stick_count,
            first_center_x=-control_x,pitch_x=2*control_x,
            center_y=control_z-control_size*1.1,radius=control_size*0.23,
            recess_depth=depth,cut_center_z=cz))))
    if system_count:
        tools.append(face_tool(button_row(dict(count=system_count,
            first_center_x=-0.5*(system_count-1)*button_radius*3,pitch_x=button_radius*3,
            center_y=body_height*0.10,radius=button_radius*0.6,recess_depth=depth,cut_center_z=cz))))
    if touchpad_present:
        tools.append(face_tool(display_panel(dict(width=body_width*0.16,height=body_height*0.14,
            recess_depth=depth,center_x=0,center_y=body_height*0.18,cut_center_z=cz))))
    return tools


def tools():
    out=front_tools()+[battery_bay(door_params())]
    if media_kind!="none":
        out.append(media_slot(media_params()))
    if controller_attach!="none":
        out.append(side_rail(dict(length=body_height*0.65,width=face_depth*0.35,
            depth=1 if controller_attach=="rail" else 0.6,center_y=face_depth*0.55,
            center_z=body_height*0.5,half_width=body_width/2)))
    if kickstand_present:
        out.append(kickstand_recess(stand_params()))
    if usb_present:
        out.append(edge_port(dict(shape="rect",edge="bottom",width=9,height=3.2,radius=0,
            depth=5,center_x=body_width*0.22,center_y=face_depth*0.5,face_z=grip_drop)))
    if jack_present:
        out.append(edge_port(dict(shape="round",edge="top",width=0,height=0,radius=1.75,
            depth=6,center_x=-body_width*0.3,center_y=face_depth*0.5,face_z=body_height)))
    for count,depth,y in ((bumper_count,3,face_depth*0.3),(trigger_count,5,face_depth*0.7)):
        for i in range(count):
            out.append(edge_port(dict(shape="rect",edge="top",width=body_width*0.07,
                height=face_depth*0.2,radius=0,depth=depth,
                center_x=(i-(count-1)/2)*body_width*0.25,center_y=y,face_z=body_height)))
    for i in range(rear_count):
        out.append(rear_recess(dict(width=body_width*0.07,height=body_height*0.1,depth=1.2,
            center_x=(i-(rear_count-1)/2)*body_width*0.19,center_z=body_height*0.50,
            open_y=rear_y(shape_params(),body_width*0.3),back_y=body_depth)))
    if crank_present:
        out.append(side_rail(dict(length=control_size,width=face_depth*0.3,depth=1.5,
            center_y=face_depth*0.6,center_z=body_height*0.55,half_width=body_width/2)))
    return out


def shell(side):
    inner=slab_body(shape_params(wall)).translate((0,wall,wall))
    solid=outer().cut(inner)
    for tool in tools():
        solid=solid.cut(tool)
    return solid.intersect(half_space(dict(side=side,seam_y=face_depth*0.5)))


def rear_body():
    rear=shell("rear")
    if kickstand_present:
        rear=rear.union(kickstand(stand_params()))
    if media_kind!="none":
        return cq.Workplane("XY").add(cq.Compound.makeCompound([rear.val(),media_proxy(media_params()).val()]))
    return rear


BUILDERS={"envelope":outer,"front_shell":lambda:shell("front"),
    "rear_body":rear_body,"battery_door":lambda:battery_door(door_params())}
result=BUILDERS.get(target_part,outer)()
